/* Privacy-friendly aggregate analytics via GoatCounter.
 * No cookies, no fingerprinting, no document contents.
 * Blocked by ad blockers; that is acceptable.
 */
(function () {
  "use strict";
  var script = document.createElement("script");
  script.async = true;
  script.src = "https://gc.zgo.at/count.js";
  script.setAttribute("data-goatcounter", "https://preflight-a11y.goatcounter.com/count");
  document.body.appendChild(script);
})();
